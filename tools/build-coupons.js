// Insert (or refresh) the data-driven "spend less" section on /coupons from the menu data.
// Usage: node tools/build-coupons.js
const fs = require('fs');
const path = require('path');
const { items, byName, money, toppingPrice } = require('./menu-data');

const FILE = path.join(__dirname, '..', 'coupons.html');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const priced = items.filter((i) => i.price != null && i.category !== 'cat-beverages');
const plates = priced.filter((i) => ['cat-classic-egg-breakfasts', 'cat-all-star-specials', 'cat-hashbrown-bowls', 'cat-lunch-dinner-bowls', 'cat-dinners'].includes(i.category)).sort((a, b) => a.price - b.price).slice(0, 5);
const under6 = priced.filter((i) => i.price <= 6 && i.cal >= 400).sort((a, b) => b.cal / b.price - a.cal / a.price).slice(0, 8);
const bestProtein = priced.filter((i) => i.protein >= 20).sort((a, b) => b.protein / b.price - a.protein / a.price).slice(0, 5);
const as = byName['All-Star Special with Bacon'], egg = byName['Two Egg Breakfast with Bacon'], waffle = byName['Classic Waffle'];
const separate = egg.price + waffle.price;
const hb = byName['Hashbrowns (Regular)'], sc = byName['Hashbrowns Scattered, Smothered & Covered'];

const li = (a, b) => `
              <li class="flex justify-between gap-4 border-b border-gray-100 pb-2 last:border-0"><span>${a}</span><span class="font-bold text-[#1C1410] whitespace-nowrap">${b}</span></li>`;
const card = (title, body) => `
          <div class="bg-white rounded-3xl border-2 border-gray-200 p-6 sm:p-8 shadow-xs">
            <h3 class="text-lg sm:text-xl font-extrabold text-[#1C1410] mb-3 font-heading">${title}</h3>
            ${body}
          </div>`;

const section = `    <!-- ================= SPEND LESS (generated by tools/build-coupons.js) ================= -->
    <section class="py-14 bg-white border-b border-gray-200 font-sans" id="spend-less">
      <div class="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8">
        <div class="mb-8 max-w-3xl">
          <h2 class="text-2xl sm:text-3xl font-extrabold text-[#1C1410] font-heading tracking-tight">How to Spend Less Without a Coupon</h2>
          <p class="text-gray-700 text-sm sm:text-base mt-2">Using typical 2026 prices (they vary by location), these orders give the most food for the money.</p>
        </div>
        <div class="grid grid-cols-1 md:grid-cols-2 gap-6">${card('The All-Star Special is the best-value plate', `<p class="text-gray-700 text-sm sm:text-base leading-relaxed mb-3">Ordered separately, a two egg breakfast with bacon (${money(egg.price)}) plus a classic waffle (${money(waffle.price)}) comes to about ${money(separate)}. The All-Star Special puts the same food on one plate for about ${money(as.price)}, a saving of roughly ${money(separate - as.price)}.</p>
            <p class="text-sm text-gray-600">See the <a class="font-bold underline text-[#1C1410]" href="/blog/waffle-house-all-star-special/">All-Star Special price guide</a>.</p>`)}${card('Lowest-priced full plates', `<ul class="space-y-2 text-sm sm:text-base text-gray-700">${plates.map((i) => li(esc(i.name), money(i.price))).join('')}
            </ul>`)}${card('Filling orders for about $6 or less', `<ul class="space-y-2 text-sm sm:text-base text-gray-700">${under6.map((i) => li(esc(i.name), `${money(i.price)} &middot; ${i.cal} cal`)).join('')}
            </ul>`)}${card('Most protein for the money', `<ul class="space-y-2 text-sm sm:text-base text-gray-700">${bestProtein.map((i) => li(esc(i.name), `${i.protein}g &middot; ${money(i.price)}`)).join('')}
            </ul>`)}${card('Watch the hashbrown toppings', `<p class="text-gray-700 text-sm sm:text-base leading-relaxed">Each topping usually adds about ${money(toppingPrice)}. A regular order of hashbrowns is about ${money(hb.price)}, while scattered, smothered and covered is about ${money(sc.price)}, and ordering them all the way is about ${money(byName['Hashbrowns All The Way'].price)}.</p>`)}${card('Prices change by location', `<p class="text-gray-700 text-sm sm:text-base leading-relaxed">The same order costs a few dollars more at some restaurants near highways, airports and in bigger cities. Compare typical prices and price ranges on the <a class="font-bold underline text-[#1C1410]" href="/prices-by-state">prices by state</a> page before you go.</p>`)}
        </div>
      </div>
    </section>

`;

let h = fs.readFileSync(FILE, 'utf8');
const nl = h.includes('\r\n') ? '\r\n' : '\n';
h = h.replace(/\r\n/g, '\n');
h = h.replace(/    <!-- =+ SPEND LESS \(generated[\s\S]*?<\/section>\n\n/, '');
const at = h.search(/    <!-- =+ 3\. HOW TO REDEEM GUIDE/);
if (at < 0) throw new Error('HOW TO REDEEM marker not found');
h = h.slice(0, at) + section + h.slice(at);
fs.writeFileSync(FILE, h.replace(/\n/g, nl));
console.log(`coupons: spend-less section (All-Star saves ${money(separate - as.price)})`);
