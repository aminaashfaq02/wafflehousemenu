// Insert (or refresh) the printable one-page menu on /menu/pdf/ from the menu data.
// Usage: node tools/build-printable.js
const fs = require('fs');
const path = require('path');
const { categories, items, money } = require('./menu-data');

const FILE = path.join(__dirname, '..', 'menu', 'pdf', 'index.html');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const blocks = categories.map((cat) => `
          <div class="print-block break-inside-avoid mb-6">
            <h3 class="font-heading font-black text-[#1C1410] text-base uppercase tracking-wide border-b-2 border-[#F59E0B] pb-1 mb-2">${esc(cat.title)}</h3>
            <ul class="text-sm">${cat.items.map((it) => `
              <li class="flex items-baseline gap-2 py-0.5"><span class="text-[#1C1410]">${esc(it.name)}</span><span class="flex-1 border-b border-dotted border-gray-400 translate-y-[-3px]" aria-hidden="true"></span><span class="font-bold text-[#1C1410] whitespace-nowrap">${money(it.price)}</span><span class="text-gray-600 whitespace-nowrap w-16 text-right">${it.cal} cal</span></li>`).join('')}
            </ul>
          </div>`).join('');

const section = `    <!-- ================= PRINTABLE MENU (generated by tools/build-printable.js) ================= -->
    <section class="py-14 md:py-16 px-4 bg-white border-b border-gray-200" id="printable-menu">
      <style media="print">
        body * { visibility: hidden !important; }
        #printable-menu, #printable-menu * { visibility: visible !important; }
        #printable-menu { position: absolute; left: 0; top: 0; width: 100%; padding: 0 !important; border: 0 !important; }
        #printable-menu .no-print { display: none !important; }
        #printable-menu .print-columns { column-count: 2; column-gap: 28px; }
        #printable-menu ul { font-size: 9.5pt; }
        @page { margin: 12mm; }
      </style>
      <div class="max-w-6xl mx-auto">
        <div class="flex flex-col sm:flex-row sm:items-end justify-between gap-4 mb-8">
          <div>
            <h2 class="text-2xl sm:text-3xl md:text-4xl font-black text-[#1C1410] font-heading tracking-tight">Printable Waffle House Menu (2026)</h2>
            <p class="text-gray-600 text-sm sm:text-base mt-1">All ${items.length} items with typical prices and calories. Prices vary by location; compiled by Waffle Guide, updated November 3, 2026.</p>
          </div>
          <button type="button" onclick="window.print()" class="no-print inline-flex items-center justify-center gap-2 font-heading font-bold text-sm sm:text-base px-6 py-3.5 rounded-2xl bg-[#1C1410] hover:bg-gray-800 text-white transition-colors">Print this menu</button>
        </div>
        <div class="print-columns sm:columns-2 lg:columns-3 gap-8">${blocks}
        </div>
        <p class="text-xs text-gray-600 mt-4">&ldquo;Varies&rdquo; means no reliable typical price was found. Waffle Guide is not affiliated with Waffle House, Inc.</p>
      </div>
    </section>

`;

let h = fs.readFileSync(FILE, 'utf8');
const nl = h.includes('\r\n') ? '\r\n' : '\n';
h = h.replace(/\r\n/g, '\n');
// drop a previous copy, then insert before the "Discover more" section
h = h.replace(/    <!-- =+ PRINTABLE MENU \(generated[\s\S]*?<\/section>\n\n/, '');
const at = h.search(/    <!-- =+ DISCOVER MORE/);
if (at < 0) throw new Error('DISCOVER MORE marker not found');
h = h.slice(0, at) + section + h.slice(at);

// hero, how-to-print and FAQ wording point at the printable menu
const swaps = [
  ['If you want a menu to print, our independent menu guide prints cleanly from any browser.', 'If you want a menu to print, use the one-page printable menu below, with typical prices and calories for every item.'],
  ['<a href="/menu" class="inline-flex items-center justify-center gap-2 font-heading font-bold text-sm sm:text-base px-6 py-3.5 rounded-2xl transition-colors bg-[#1C1410] hover:bg-gray-800 text-white">Open our printable menu guide</a>', '<a href="#printable-menu" class="inline-flex items-center justify-center gap-2 font-heading font-bold text-sm sm:text-base px-6 py-3.5 rounded-2xl transition-colors bg-[#1C1410] hover:bg-gray-800 text-white">Go to the printable menu</a>'],
  ['<h2 class="text-2xl font-extrabold font-heading text-[#1C1410] mb-4">How to print our menu guide</h2>', '<h2 class="text-2xl font-extrabold font-heading text-[#1C1410] mb-4">How to print the menu</h2>'],
  ['<li>Open our <a href="/menu" class="font-bold underline text-[#1C1410]">menu guide</a>.</li>\n            <li>Press Ctrl + P (Cmd + P on a Mac).</li>', '<li>Go to the <a href="#printable-menu" class="font-bold underline text-[#1C1410]">printable menu</a> below.</li>\n            <li>Press the Print this menu button, or Ctrl + P (Cmd + P on a Mac).</li>'],
];
for (const [a, b] of swaps) if (h.includes(a)) h = h.split(a).join(b);
const oldQ = 'Open our menu guide, press Ctrl + P (Cmd + P on a Mac), choose US Letter or A4, and select “Fit to printable area”.';
const newQ = 'Use the printable menu on this page: press the Print this menu button (or Ctrl + P, Cmd + P on a Mac), choose US Letter or A4, and only the menu is printed.';
h = h.split(oldQ).join(newQ);
h = h.split(oldQ.replace(/“/g, '&ldquo;').replace(/”/g, '&rdquo;')).join(newQ);
fs.writeFileSync(FILE, h.replace(/\n/g, nl));
console.log('menu/pdf: printable menu with', items.length, 'items');
